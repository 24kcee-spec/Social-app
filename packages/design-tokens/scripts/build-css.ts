import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dark, elevation, font, light, motion, radius, space, touch, type ColorTokens } from "../src/index.ts";

const kebab = (s: string) => s.replace(/[A-Z0-9]/g, (m) => `-${m.toLowerCase()}`);
const colorVars = (c: ColorTokens, pad: string) => Object.entries(c).map(([k, v]) => `${pad}--${kebab(k)}:${v};`).join("\n");

const css = `/* GENERATED by packages/design-tokens (pnpm --filter @sp/design-tokens build:css). Do not edit by hand. */
:root {
${colorVars(light, "  ")}
${Object.entries(space).map(([k, v]) => `  --space-${k}:${v}px;`).join("\n")}
${Object.entries(radius).map(([k, v]) => `  --radius-${k}:${v}px;`).join("\n")}
  --shadow-1:${elevation[1].css};
  --shadow-2:${elevation[2].css};
  --font-sans:${font.sans};
  --font-display:${font.display};
  --dur-fast:${motion.fast}ms;
  --dur-base:${motion.base}ms;
  --touch:${touch.min}px;
  color-scheme:light;
}
@media (prefers-color-scheme: dark) {
  :root:not([data-theme="light"]) {
${colorVars(dark, "    ")}
    color-scheme:dark;
  }
}
:root[data-theme="dark"] {
${colorVars(dark, "  ")}
  color-scheme:dark;
}
`;
writeFileSync(fileURLToPath(new URL("../../../apps/web/app/tokens.css", import.meta.url)), css);
console.log("wrote apps/web/app/tokens.css");
